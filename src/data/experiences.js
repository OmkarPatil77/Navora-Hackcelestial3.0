/**
 * Filter helper to get experiences for a given destination
 */
export function getExperiencesByDestination(destinationQuery = "Goa") {
  if (!destinationQuery) return allExperiences.filter(e => e.destinationId === "goa")
  
  const query = destinationQuery.toLowerCase().trim()
  const matched = allExperiences.filter(e => 
    e.destinationId.toLowerCase().includes(query) ||
    e.destination.toLowerCase().includes(query) ||
    query.includes(e.destinationId.toLowerCase()) ||
    query.includes(e.destination.toLowerCase())
  )

  return matched.length > 0 ? matched : allExperiences.filter(e => e.destinationId === "goa")
}

